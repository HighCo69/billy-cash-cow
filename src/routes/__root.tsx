function ErrorComponent({ error, reset }: import("@tanstack/react-router").ErrorComponentProps) {
  console.error(error);
  const router = useRouter();
  useEffect(() => {
    reportLovableError(error, { boundary: "tanstack_root_error_component" });
  }, [error]);

  return (
    <div className="flex min-h-screen items-center justify-center bg-background px-4">
      <div className="max-w-md text-center">
        <h1 className="text-xl font-semibold tracking-tight text-foreground">
          Da ist eine Kuh umgefallen
        </h1>
        <p className="mt-2 text-sm text-muted-foreground">
          Die Seite konnte nicht geladen werden. Versuch es nochmal.
        </p>
        <div className="mt-6 flex flex-wrap justify-center gap-2">
          <button
            onClick={() => {
              router.invalidate();
              reset();
            }}
            className="inline-flex items-center justify-center rounded-full border-2 border-ink bg-primary px-4 py-2 text-sm font-bold text-primary-foreground"
          >
            Nochmal versuchen
          </button>
          <a
            href="/"
            className="inline-flex items-center justify-center rounded-full border-2 border-ink bg-card px-4 py-2 text-sm font-bold text-foreground"
          >
            Zur Startseite
          </a>
        </div>
      </div>
    </div>
  );
}

